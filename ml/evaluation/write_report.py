"""Generate docs/MODEL_EVALUATION_REPORT.md and the README results block from the saved evaluation outputs,
so that no number in the documentation is typed by hand.

  python ml/evaluation/write_report.py
"""
from __future__ import annotations

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
EVAL = ROOT / "ml/artifacts/evaluation"
SETS = [("test", "PlantVillage test (internal)"), ("external_test_plantdoc", "PlantDoc test (field)"),
        ("external_test_tomato_pk_field", "Tomato field, Pakistan (field)")]


def p(v, d=1):
    return "—" if v is None else f"{v * 100:.{d}f}%"


def nice(c):
    a, b = c.split("___")
    return f"{a.replace('_(maize)', '').replace('_(including_sour)', '').replace(',_bell', ' (bell)').replace('_', ' ')} — {b.replace('_', ' ').strip()}"


def main():
    s = json.loads((EVAL / "summary.json").read_text())
    sel_run = s["selection"]["selected_run"]
    runs = {m["run"]: json.loads((EVAL / m["run"] / "metrics.json").read_text()) for m in s["models"]}
    sel = runs[sel_run]
    selrow = next(m for m in s["models"] if m["selected"])
    L = []
    w = L.append
    w("# Model Evaluation Report\n")
    w(f"_Generated by `ml/evaluation/write_report.py` from `ml/artifacts/evaluation/` on {s['generated_at']}. "
      "Every number below comes from saved model predictions on held-out data._\n")
    w("## 1. Summary\n")
    t = sel["results"]["test"]
    pdoc = sel["results"]["external_test_plantdoc"]
    tom = sel["results"]["external_test_tomato_pk_field"]
    w(f"* **Deployed model:** {selrow['display_name']} (`{sel_run}`), {sel['parameters_m']:.1f} M parameters, "
      f"{sel['img_size']} px input, {sel['checkpoint_mb']:.0f} MB checkpoint, "
      f"{sel['latency']['cpu']['batch1_ms_mean']:.0f} ms mean CPU latency (batch 1).")
    w(f"* **Selection rule:** {s['selection']['rule']}")
    w(f"* **Internal (PlantVillage test, n={t['n']:,}):** accuracy {p(t['accuracy'], 2)}, macro-F1 {p(t['macro_f1'], 2)}, "
      f"macro precision {p(t['macro_precision'], 2)}, macro recall {p(t['macro_recall'], 2)}, weighted F1 {p(t['weighted_f1'], 2)}.")
    w(f"* **External — PlantDoc test (n={pdoc['n']}):** accuracy {p(pdoc['accuracy'])}, macro-F1 {p(pdoc['macro_f1'])}, "
      f"crop accuracy {p(pdoc['crop_accuracy'])}, top-3 {p(pdoc['top3_accuracy'])}.")
    w(f"* **External — Tomato field, Pakistan (n={tom['n']:,}):** accuracy {p(tom['accuracy'])}, macro-F1 {p(tom['macro_f1'])}, "
      f"top-3 {p(tom['top3_accuracy'])}.")
    w(f"* **Internal → external gap:** {p(t['accuracy'] - pdoc['accuracy'])} absolute accuracy drop on PlantDoc and "
      f"{p(t['accuracy'] - tom['accuracy'])} on the tomato field set. Lab accuracy must not be read as field accuracy.\n")

    w("## 2. Model comparison\n")
    w("Validation columns drove model selection; test columns were computed once afterwards.\n")
    w("| Model | Trained on | Params | Epochs (best) | Train min | Val macro-F1 | Ext-val macro-F1 | "
      + " | ".join(f"{n} acc / macro-F1" for _, n in SETS) + " | CPU ms | MPS ms | Size MB |")
    w("|---|---|---:|---:|---:|---:|---:|" + "---:|" * len(SETS) + "---:|---:|---:|")
    for m in s["models"]:
        r = runs[m["run"]]
        cells = " | ".join(f"{p(r['results'][k]['accuracy'])} / {p(r['results'][k]['macro_f1'])}" for k, _ in SETS)
        mps = r["latency"].get("mps", {}).get("batch1_ms_mean")
        w(f"| {'**' if m['selected'] else ''}{m['display_name']}{'** (deployed)' if m['selected'] else ''} | {r['trained_on']} | "
          f"{r['parameters_m']:.1f} M | {r['epochs_trained']} ({r['best_epoch']}) | {r['train_seconds'] / 60:.0f} | "
          f"{p(r['results']['validation']['macro_f1'], 2)} | {p(r['results']['external_validation']['macro_f1'])} | {cells} | "
          f"{r['latency']['cpu']['batch1_ms_mean']:.0f} | {'—' if mps is None else f'{mps:.0f}'} | {r['checkpoint_mb']:.0f} |")
    w("\n![comparison](../ml/artifacts/evaluation/model_comparison.png)\n")
    w("![curves](../ml/artifacts/evaluation/training_curves.png)\n")

    w("### Full metric table per model and set\n")
    w("| Model | Set | n | Acc | Macro P | Macro R | Macro F1 | Weighted F1 | Crop acc | Top-3 | ECE raw → cal |")
    w("|---|---|---:|---:|---:|---:|---:|---:|---:|---:|---|")
    for m in s["models"]:
        r = runs[m["run"]]
        for k in ("validation", "external_validation", "test", "external_test_plantdoc", "external_test_tomato_pk_field"):
            x = r["results"][k]
            w(f"| {m['display_name']} | {k} | {x['n']:,} | {p(x['accuracy'], 2)} | {p(x['macro_precision'], 2)} | {p(x['macro_recall'], 2)} | "
              f"{p(x['macro_f1'], 2)} | {p(x['weighted_f1'], 2)} | {p(x['crop_accuracy'])} | {p(x['top3_accuracy'])} | "
              f"{x['ece_uncalibrated']:.3f} → {x['ece_calibrated']:.3f} |")

    w("\n## 3. Calibration and uncertainty (deployed model)\n")
    w(f"* Temperature T = **{sel['temperature']:.3f}** (fitted on validation + external validation, domains weighted equally).")
    w(f"* Confident threshold τ = **{sel['confidence_threshold']:.3f}**; reject threshold τ_r = **{sel['reject_threshold']:.3f}**.")
    w(f"* Rule applied: {sel['threshold_rule']}.")
    w("\n| Set | Coverage at τ | Accuracy on answered | Accuracy on withheld | Unrecognized rate | AURC |")
    w("|---|---:|---:|---:|---:|---:|")
    for k in ("validation", "external_validation", "test", "external_test_plantdoc", "external_test_tomato_pk_field"):
        x = sel["results"][k]["selective_at_threshold"]
        w(f"| {k} | {p(x['coverage'])} | {p(x['selective_accuracy'])} | {p(x.get('rejected_accuracy'))} | "
          f"{p(sel['results'][k]['unrecognized_rate'])} | {sel['risk_coverage'][k]['aurc']:.3f} |")
    w("\nSoftmax confidence — even calibrated — does **not** guarantee correctness, especially under domain shift: the "
      "rows above show how often confident answers are still wrong on field photos.\n")
    run_dir = f"../ml/artifacts/evaluation/{sel_run}"
    w(f"![risk coverage]({run_dir}/risk_coverage.png)\n")
    w(f"| Reliability — PlantVillage test | Reliability — PlantDoc test | Reliability — Tomato field |\n|---|---|---|\n"
      f"| ![]({run_dir}/reliability_test.png) | ![]({run_dir}/reliability_external_test_plantdoc.png) | ![]({run_dir}/reliability_external_test_tomato_pk_field.png) |\n")

    w("## 4. Confusion matrices (deployed model)\n")
    w(f"![cm]({run_dir}/confusion_matrix_test_normalized.png)\n")
    w(f"Raw counts: [`confusion_matrix_test.png`]({run_dir}/confusion_matrix_test.png). External sets (rows/cols limited to classes that occur):\n")
    w(f"| PlantDoc test | Tomato field |\n|---|---|\n| ![]({run_dir}/confusion_matrix_external_test_plantdoc_normalized.png) | ![]({run_dir}/confusion_matrix_external_test_tomato_pk_field_normalized.png) |\n")

    w("## 5. Per-class results (deployed model)\n")
    for k, name in SETS:
        pc = sel["results"][k]["per_class"]
        w(f"### {name}\n")
        w("| Class | Precision | Recall | F1 | Support |\n|---|---:|---:|---:|---:|")
        for c, v in sorted(pc.items(), key=lambda kv: kv[1]["f1"]):
            w(f"| {nice(c)} | {p(v['precision'])} | {p(v['recall'])} | {p(v['f1'])} | {v['support']} |")
        w("")
        w("Most frequent confusions: " + "; ".join(f"{nice(c['true'])} → {nice(c['pred'])} ({c['count']})" for c in sel["results"][k]["top_confusions"][:6]) + "\n")
        w(f"Classification report: [`classification_report_{k}.txt`]({run_dir}/classification_report_{k}.txt)\n")

    w("## 6. Error analysis\n")
    w("The most confident mistakes of the deployed model (real images):\n")
    w(f"| PlantVillage test | PlantDoc test | Tomato field |\n|---|---|---|\n| ![]({run_dir}/misclassified_test.png) | "
      f"![]({run_dir}/misclassified_external_test_plantdoc.png) | ![]({run_dir}/misclassified_external_test_tomato_pk_field.png) |\n")
    w("<!-- ANALYSIS:START -->\n<!-- ANALYSIS:END -->\n")

    w("## 7. Explainability\n")
    w("![gradcam](../ml/artifacts/evaluation/gradcam_examples.png)\n")
    w("Grad-CAM of the deployed model on PlantVillage test images (top rows) and field images (bottom rows), computed with "
      "the same code path the API uses. Heat-maps indicate influence on the class score, not correctness.\n")

    w("## 8. Latency and size\n")
    w("| Model | CPU batch-1 mean / p50 / p95 (ms) | MPS batch-1 mean (ms) | Parameters | Checkpoint |\n|---|---|---:|---:|---:|")
    for m in s["models"]:
        r = runs[m["run"]]
        c = r["latency"]["cpu"]
        mps = r["latency"].get("mps", {}).get("batch1_ms_mean")
        w(f"| {m['display_name']} | {c['batch1_ms_mean']:.1f} / {c['batch1_ms_p50']:.1f} / {c['batch1_ms_p95']:.1f} | "
          f"{'—' if mps is None else f'{mps:.1f}'} | {r['parameters_m']:.1f} M | {r['checkpoint_mb']:.0f} MB |")
    w("\nMeasured on the Apple M1 development machine (8 GB, other applications running), 40 timed runs after 5 warm-up runs.")
    report = "\n".join(L) + "\n"
    out = ROOT / "docs/MODEL_EVALUATION_REPORT.md"
    if out.exists():  # keep hand-written analysis between markers
        old = out.read_text()
        m = re.search(r"<!-- ANALYSIS:START -->.*?<!-- ANALYSIS:END -->", old, re.S)
        if m:
            report = report.replace("<!-- ANALYSIS:START -->\n<!-- ANALYSIS:END -->", m.group(0))
    out.write_text(report)

    readme = ROOT / "README.md"
    block = ["<!-- RESULTS:START -->", "## Results (held-out data)\n",
             f"Deployed: **{selrow['display_name']}** — selected on validation data only.\n",
             "| Model | " + " | ".join(f"{n} acc / macro-F1" for _, n in SETS) + " | CPU ms |", "|---|" + "---:|" * (len(SETS) + 1)]
    for m in s["models"]:
        r = runs[m["run"]]
        block.append(f"| {m['display_name']}{' ⭐' if m['selected'] else ''} | " + " | ".join(
            f"{p(r['results'][k]['accuracy'])} / {p(r['results'][k]['macro_f1'])}" for k, _ in SETS) + f" | {r['latency']['cpu']['batch1_ms_mean']:.0f} |")
    block += ["", "Lab-style accuracy does **not** carry over to field photos; the app therefore flags uncertain results and "
              "withholds advice below a validation-selected confidence threshold. Details: "
              "[docs/MODEL_EVALUATION_REPORT.md](docs/MODEL_EVALUATION_REPORT.md).", "",
              "![screens](docs/screenshots/desktop-03-results-en.png)", "<!-- RESULTS:END -->"]
    txt = readme.read_text()
    readme.write_text(re.sub(r"<!-- RESULTS:START -->.*?<!-- RESULTS:END -->", "\n".join(block), txt, flags=re.S))
    print("report + README updated")


if __name__ == "__main__":
    main()
