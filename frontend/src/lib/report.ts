import type { Advisory, Lang } from "./api";
import type { StoredResult } from "./result-store";

const esc = (s: string) => s.replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" })[c]!);
const list = (xs?: string[] | null) => (xs?.length ? `<ul>${xs.map((x) => `<li>${esc(x)}</li>`).join("")}</ul>` : "");

const L = {
  en: { title: "KrishiGuard AI — Diagnosis report", crop: "Crop", cond: "Condition", conf: "Confidence (calibrated)", status: "Result status",
    cands: "Top possibilities", sym: "Symptoms", causes: "Causes", prev: "Prevention", org: "Organic options", chem: "Chemical options",
    src: "Sources", xai: "Grad-CAM (regions that influenced the model)", model: "Model", note: "Advisory shown only for confident results.",
    disc: "This report is generated by an AI decision-support tool and is not a substitute for an agricultural expert. Confirm the diagnosis with your local KVK / agriculture officer and always follow the registered product label." },
  hi: { title: "KrishiGuard AI — जाँच रिपोर्ट", crop: "फसल", cond: "स्थिति", conf: "भरोसा (कैलिब्रेटेड)", status: "नतीजे की स्थिति",
    cands: "मुख्य संभावनाएँ", sym: "लक्षण", causes: "कारण", prev: "बचाव", org: "जैविक उपाय", chem: "रासायनिक उपाय",
    src: "स्रोत", xai: "Grad-CAM (फ़ोटो के वे हिस्से जिन्होंने मॉडल को प्रभावित किया)", model: "मॉडल", note: "सलाह केवल भरोसेमंद नतीजों पर दिखाई जाती है।",
    disc: "यह रिपोर्ट AI सहायक उपकरण से बनी है, यह कृषि विशेषज्ञ का विकल्प नहीं है। अपने नज़दीकी KVK / कृषि अधिकारी से पुष्टि करें और हमेशा पंजीकृत उत्पाद के लेबल का पालन करें।" },
};

export function buildReportHtml(o: { stored: StoredResult; advisory: Advisory | null; lang: Lang; names: { crop: string; disease: string }; statusTitle: string; statusMsg: string }) {
  const { stored, advisory: a, lang } = o;
  const p = stored.prediction;
  const l = L[lang];
  const pct = (v: number) => `${(v * 100).toFixed(1)}%`;
  const xai = p.explanation
    ? `<h2>${l.xai}</h2><div class="row"><img src="data:image/png;base64,${p.explanation.model_input_png}"><img src="data:image/png;base64,${p.explanation.heatmap_png}"><img src="data:image/png;base64,${p.explanation.overlay_png}"></div><p class="muted">${esc(p.explanation.note)}</p>`
    : "";
  const adv = a
    ? `${a.summary ? `<p>${esc(a.summary)}</p>` : ""}<h2>${l.sym}</h2>${list(a.symptoms)}<h2>${l.causes}</h2>${list(a.causes)}<h2>${l.prev}</h2>${list(a.prevention)}
       ${a.organic_treatment ? `<h2>${l.org}</h2>${list(a.organic_treatment)}` : ""}
       ${a.chemical_treatment ? `<h2>${l.chem}</h2>${list(a.chemical_treatment.items)}${a.chemical_label_notice ? `<p class="warn">${esc(a.chemical_label_notice)}</p>` : ""}` : ""}
       <h2>${l.src}</h2><ul>${a.sources.map((s) => `<li><a href="${esc(s.url)}">${esc(s.title)}</a> — ${esc(s.publisher)}</li>`).join("")}</ul>`
    : `<p class="warn">${l.note}</p>`;
  return `<!doctype html><html lang="${lang}"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>${l.title}</title>
<style>body{font-family:system-ui,"Noto Sans Devanagari",sans-serif;max-width:860px;margin:32px auto;padding:0 20px;color:#1d2a22;line-height:1.5}
h1{font-size:24px;margin:0}h2{font-size:17px;margin:22px 0 6px;color:#2f6e46}.muted{color:#64706a;font-size:13px}
.card{border:1px solid #dfe4da;border-radius:12px;padding:16px;margin:16px 0}.grid{display:grid;grid-template-columns:200px 1fr;gap:16px;align-items:start}
.grid img{width:200px;border-radius:10px}.row{display:flex;gap:8px}.row img{width:32%;border-radius:8px}
.warn{background:#fff6dd;border:1px solid #f0d58a;padding:8px 12px;border-radius:8px;font-size:13px}table{border-collapse:collapse}td{padding:3px 12px 3px 0}
.disc{margin-top:28px;font-size:12px;color:#64706a;border-top:1px solid #dfe4da;padding-top:12px}@media(max-width:600px){.grid{grid-template-columns:1fr}}</style></head>
<body><h1>${l.title}</h1><p class="muted">${new Date(stored.createdAt).toLocaleString(lang === "hi" ? "hi-IN" : "en-IN")} · ${l.model}: ${esc(p.model_version)}</p>
<div class="card grid"><img src="${stored.image}" alt=""><div><table>
<tr><td><b>${l.status}</b></td><td>${esc(o.statusTitle)}</td></tr>
<tr><td><b>${l.crop}</b></td><td>${esc(o.names.crop)}</td></tr><tr><td><b>${l.cond}</b></td><td>${esc(o.names.disease)}</td></tr>
<tr><td><b>${l.conf}</b></td><td>${pct(p.confidence)}</td></tr></table><p class="muted">${esc(o.statusMsg)}</p>
<b>${l.cands}</b><ol>${p.top_k.map((k) => `<li>${esc(k.crop)} — ${esc(k.disease)}: ${pct(k.probability)}</li>`).join("")}</ol></div></div>
${xai}${adv}<p class="disc">${l.disc}</p></body></html>`;
}
